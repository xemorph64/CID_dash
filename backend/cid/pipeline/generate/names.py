def _curated_script_form(canonical_name: str, script: str) -> str | None:
    """Compose a curated script rendering of a "First [Middle...] Last" name.

    Returns None (caller falls back to transliterate_name()) unless every
    token has a curated pair in that script.
    """
    tokens = canonical_name.split()
    first_map = _FIRST_NAME_SCRIPTS[script]
    last_map = _SURNAME_SCRIPTS[script]
    parts = []
    for i, tok in enumerate(tokens):
        pair = last_map.get(tok) if i == len(tokens) - 1 and len(tokens) > 1 else first_map.get(tok)
        if pair is None:
            return None
        parts.append(pair)
    return " ".join(parts)


# --- People generation -------------------------------------------------------


def _random_dob(rng: random.Random) -> datetime.date:
    age = rng.randint(*ADULT_AGE_RANGE)
    year = REFERENCE_YEAR - age
    month = rng.randint(1, 12)
    day = rng.randint(1, calendar.monthrange(year, month)[1])
    return datetime.date(year, month, day)


def make_people(n: int, rng: random.Random, *, start_id: int = 1) -> list[TruePerson]:
    """Deterministically generate `n` fictional people.

    Curated first-name/surname lists are the primary source; Faker (en_IN,
    hi_IN) fills in the remainder for volume.
    """
    fake = Faker(["en_IN", "hi_IN"])
    fake.seed_instance(rng.getrandbits(32))

    people = []
    for i in range(n):
        person_id = f"PERSON_{start_id + i:06d}"
        if rng.random() < 0.85:
            name = f"{rng.choice(FIRST_NAMES)} {rng.choice(SURNAMES)}"
        else:
            # hi_IN's own name() renders in Devanagari; canonical_name must
            # stay Latin script, so force the en_IN factory explicitly.
            name = fake["en_IN"].name()
        people.append(
            TruePerson(
                person_id=person_id,
                canonical_name=name,
                dob=_random_dob(rng),
                home_town=rng.choice(TOWNS),
            )
        )
    return people


# --- Variant generation -------------------------------------------------------


def _pick_translit_script(rng: random.Random) -> str:
    # prd §7: mostly Devanagari, a few Tamil/Bengali forms.
    return rng.choices(["Deva", "Taml", "Beng"], weights=[0.7, 0.15, 0.15], k=1)[0]


def variants_for(person: TruePerson, rng: random.Random, count: int) -> list[NameVariant]:
    """Produce `count` (2-5) plausible renderings of one person across sources."""
    n = max(2, min(5, count))
    tokens = person.canonical_name.split()
    first, rest = tokens[0], tokens[1:]
    surname = tokens[-1] if rest else ""

    exact = NameVariant(surface=person.canonical_name, script="Latn", kind="exact")

    others: list[NameVariant] = []

    wobble = SURNAME_WOBBLES.get(surname.lower())
    if wobble:
        others.append(
            NameVariant(surface=" ".join([first, *rest[:-1], wobble]), script="Latn", kind="spelling")
        )

    for ab in ABBREVIATIONS.get(first.lower(), []):
        others.append(NameVariant(surface=" ".join([ab, *rest]), script="Latn", kind="abbreviation"))

    others.append(
        NameVariant(surface=f"{first[0]}. {' '.join(rest)}".strip(), script="Latn", kind="initials")
    )

    formal = FORMAL_SURNAME_MAP.get(surname.lower())
    if formal:
        others.append(
            NameVariant(surface=" ".join([first, *rest[:-1], formal]), script="Latn", kind="formal_surname")
        )

    # Every non-Latin surface must be curated, therefore correct — no
    # transliterate_name() fallback here. If there's no curated pair for
    # this name in the chosen script, this person just gets no script
    # variant this round (the Latin candidates above still apply).
    script = _pick_translit_script(rng)
    surface = _curated_script_form(person.canonical_name, script)
    if surface is not None:
        others.append(NameVariant(surface=surface, script=script, kind="transliteration"))

    # De-duplicate by surface, preserving order (no set-based ordering).
    seen: list[str] = []
    deduped: list[NameVariant] = []
    for v in others:
        if v.surface not in seen:
            seen.append(v.surface)
            deduped.append(v)

    if len(deduped) > n - 1:
        idx = sorted(rng.sample(range(len(deduped)), n - 1))
        deduped = [deduped[i] for i in idx]

    return [exact, *deduped]


