# Word-final virama/pulli left behind by naive ITRANS transliteration
# (Devanagari, Tamil, Bengali) — stripping it is a cosmetic floor, not a
# correctness fix; see transliterate_name()'s docstring.
_TRAILING_VIRAMAS = "्்্"


def transliterate_name(name: str, script: str) -> str:
    """Render a Latin name into the given Indic script.

    Naive ITRANS transliteration (used here only as a fallback for names with
    no curated script form — chiefly Faker filler names). It does not
    reproduce how a name is actually spelled in that script by a human: it
    drops long vowels at word ends and leaves a stray word-final virama. The
    virama is stripped below since it is the most visible artifact; the
    curated FIRST_NAME_SCRIPTS/SURNAME_SCRIPTS pairs are what actually fix
    the common-name case — see the Mohammad Ali trap, which uses a curated
    literal for the same reason.
    """
    scheme = _TRANSLITERATION_SCHEMES[script]
    raw = transliterate(name.lower(), sanscript.ITRANS, scheme)
    return " ".join(w.rstrip(_TRAILING_VIRAMAS) for w in raw.split())


